#!/usr/bin/env bash

###############################################################################
# File Operations
###############################################################################

file_copy() {

    local SRC="$1"
    local DST="$2"

    cp -R "$SRC" "$DST"

}

###############################################################################

file_remove() {

    local FILE="$1"

    [[ -e "$FILE" ]] || return 0

    rm -rf "$FILE"

}

###############################################################################

file_symlink() {

    local SRC="$1"
    local DST="$2"

    ln -sfn "$SRC" "$DST"

}

###############################################################################

file_exists() {

    [[ -e "$1" ]]

}