#!/bin/bash

###############################################################################
# LABCTL Registry
###############################################################################

declare -A LABCTL_COMMANDS
declare -A LABCTL_SERVICES
declare -A LABCTL_PROVIDERS
declare -A LABCTL_PLUGINS

###############################################################################
# Commands
###############################################################################

register_command() {

    local NAME="$1"
    local SCRIPT="$2"

    LABCTL_COMMANDS["$NAME"]="$SCRIPT"
}

get_command() {

    echo "${LABCTL_COMMANDS[$1]}"
}

###############################################################################
# Services
###############################################################################

register_service() {

    LABCTL_SERVICES["$1"]="$2"
}

get_service() {

    echo "${LABCTL_SERVICES[$1]}"
}

###############################################################################
# Providers
###############################################################################

register_provider() {

    LABCTL_PROVIDERS["$1"]="$2"
}

get_provider() {

    echo "${LABCTL_PROVIDERS[$1]}"
}

###############################################################################
# Plugins
###############################################################################

register_plugin() {

    LABCTL_PLUGINS["$1"]="$2"
}

list_plugins() {

    printf "%s\n" "${!LABCTL_PLUGINS[@]}"
}