#!/usr/bin/env bash

###############################################################################
# LABCTL Home
###############################################################################

if [[ -n "${LABCTL_HOME:-}" ]]; then
    export LABCTL_HOME
    return 0
fi


###############################################################################
# Installed environment
###############################################################################

if [[ -d "/opt/labctl" ]]; then

    LABCTL_HOME="/opt/labctl"

    export LABCTL_HOME

    return 0

fi


###############################################################################
# Development environment
###############################################################################

LABCTL_HOME="$(
    cd "$(dirname "${BASH_SOURCE[0]}")/../.." &&
    pwd
)"

export LABCTL_HOME